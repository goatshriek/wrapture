require 'wrapture/source_set'

module Wrapture
  module Build
    # A Python project that builds a module by creating a pyproject.toml file as
    # described in PEP 517.
    class PyprojectBuild
      include Build
      include SourceSet

      # Build information for the Python module.
      attr_reader :source_set

      # Create a pyproject build for a Python module.
      def initialize(source_set)
        @source_set = source_set
      end

      # A command that will build this project.
      #
      # +python+ can be supplied to customize the Python interpreter used in the
      # build command.
      def build_commands(python: 'python3')
        ["#{python} -m build"]
      end

      # The sources for the PyProject build.
      def build_sources
        [pyproject]
      end

      # A pip install command that will install this project.
      #
      # This command assumes that the project has already been built via the
      # +build_command+.
      #
      # +python+ can be supplied to customize the Python interpreter used in the
      # build command.
      #
      # +target+ specifies the exact target to install. The default for this
      # value uses a wildcard, which is potentially dangerous. If the exact
      # wheel file name is known, it should be given to prevent unintended
      # install behavior.
      def install_commands(python: 'python3',
                           target: "dist/#{@python_build.name}-*.whl")
        ["#{python} -m pip install #{target}"]
      end

      # A pyproject.toml file that could be used to build this module.
      #
      # CMake is a common build system for C++ projects. It uses a file named
      # CMakeLists.txt to describe how to build a project, including information
      # about the source files and any dependencies required.
      def pyproject
        sources = @python_build.module_sources.map do |src|
          "\"#{src.path}\""
        end.join(', ')

        libraries = @python_build.module_links.map do |lib|
          "\"#{lib}\""
        end.join(', ')

        file = SourceFile.new('pyproject.toml')

        file.puts <<~PYPROJECTTEXT
          [project]
          name = "#{@python_build.name}"
          version = "1.0" # TODO: create a scope version number
          description= "generated by wrapture" # TODO: pass the description into the build

          [tool.setuptools]
          ext-modules = [
            {name="#{@python_build.name}", language="c", sources=[#{sources}], libraries=[#{libraries}]}
          ]

          [build-system]
          requires = ["setuptools>=74.1"]
          build-backend = "setuptools.build_meta"
        PYPROJECTTEXT

        file
      end

      # All source files in this module.
      #
      # This includes pyproject.toml as well as the sources of the underlying
      # Python module build.
      def sources
        build_sources + @source_set.sources
      end
    end
  end
end
